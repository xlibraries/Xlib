#!/usr/bin/env node
// Bundles python/**/*.py (the Pi libraries over the bench) into src/runtime/python-generated.ts, committed; the
// unit tests check it's current.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export function generate() {
    const files = [];
    const walk = (dir) => { for (const name of readdirSync(join(ROOT, 'python', dir)).sort()) { const rel = dir ? `${dir}/${name}` : name; if (statSync(join(ROOT, 'python', rel)).isDirectory()) walk(rel); else if (name.endsWith('.py')) files.push(rel); } };
    walk('');
    return `// Generated by scripts/sync-python.mjs from python/ — do not edit.\n/** Path → source of the Python libraries the runtime installs. */\nexport const PYTHON_FILES: Record<string, string> = {\n${files.map(f => `    ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(ROOT, 'python', f), 'utf8'))},`).join('\n')}\n};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(join(ROOT, 'src/runtime/python-generated.ts'), generate());
    console.log('✓ src/runtime/python-generated.ts');
}

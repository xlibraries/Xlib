#!/usr/bin/env node
// Bundles templates/<name>/<name>.{ino,hex} into src/templates/generated.ts (committed; the unit tests check it's
// current), so the app ships the sketches and their compiled hexes without a loader.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export function generate() {
    const entries = [];
    for (const name of readdirSync(join(ROOT, 'templates')).sort()) {
        const ino = join(ROOT, 'templates', name, `${name}.ino`), hex = join(ROOT, 'templates', name, `${name}.hex`);
        if (!existsSync(ino)) continue;
        entries.push(`    ${JSON.stringify(name)}: { sketch: ${JSON.stringify(readFileSync(ino, 'utf8'))}, hex: ${JSON.stringify(existsSync(hex) ? readFileSync(hex, 'utf8') : '')} },`);
    }
    return `// Generated by scripts/sync-templates.mjs from templates/ — do not edit.\nexport const TEMPLATE_CODE: Record<string, { sketch: string; hex: string }> = {\n${entries.join('\n')}\n};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(join(ROOT, 'src/templates/generated.ts'), generate());
    console.log('✓ src/templates/generated.ts');
}
